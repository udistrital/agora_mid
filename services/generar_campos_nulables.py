#!/usr/bin/env python3
"""Genera services/campos_nulables_gen.go a partir del modelo DBML.

Lee utils/generador_configuracion/entradas/agora_modelo_extendido.dbml, expande los
TablePartial referenciados con "~nombre" y lista, por tabla, las columnas NO marcadas
con [not null]. La salida es un archivo Go generado; no editarlo a mano.

Uso (desde la raíz del repositorio):
    python3 services/generar_campos_nulables.py
"""
import os
import re
import subprocess
import sys

RAIZ = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DBML = os.path.join(RAIZ, "utils", "generador_configuracion", "entradas", "agora_modelo_extendido.dbml")
SALIDA = os.path.join(RAIZ, "services", "campos_nulables_gen.go")

BLOQUE = re.compile(r"^(Table|TablePartial)\s+([\w.]+)\s*\{")
COLUMNA = re.compile(r"^\s{2}(\w+)\s+\S+(.*)$")
REFERENCIA = re.compile(r"^\s*~(\w+)\s*$")


def a_pascal(nombre):
    """Convierte un nombre de columna snake_case a PascalCase, como en la configuración."""
    return "".join(p[:1].upper() + p[1:] for p in nombre.split("_") if p)


def leer_bloques(texto):
    """Devuelve {nombre: (tipo, lineas)} para cada Table y TablePartial."""
    bloques, actual, tipo, nombre, profundidad = {}, None, None, None, 0
    for linea in texto.splitlines():
        if actual is None:
            m = BLOQUE.match(linea)
            if m:
                tipo, nombre, actual, profundidad = m.group(1), m.group(2), [], 1
            continue
        profundidad += linea.count("{") - linea.count("}")
        if profundidad <= 0:
            bloques[nombre] = (tipo, actual)
            actual = None
            continue
        actual.append(linea)
    return bloques


def columnas(nombre, bloques, visitados=frozenset()):
    """Columnas de un bloque con sus atributos, expandiendo ~partials; omite indexes."""
    if nombre not in bloques or nombre in visitados:
        return []
    _, lineas = bloques[nombre]
    salida, en_indexes, profundidad = [], False, 0
    for linea in lineas:
        if not en_indexes and linea.strip().startswith("indexes"):
            en_indexes, profundidad = True, linea.count("{") - linea.count("}")
            continue
        if en_indexes:
            profundidad += linea.count("{") - linea.count("}")
            if profundidad <= 0:
                en_indexes = False
            continue
        ref = REFERENCIA.match(linea)
        if ref:
            salida += columnas(ref.group(1), bloques, visitados | {nombre})
            continue
        col = COLUMNA.match(linea)
        if col:
            salida.append((col.group(1), col.group(2)))
    return salida


def main():
    with open(DBML, encoding="utf-8") as f:
        bloques = leer_bloques(f.read())

    por_tabla = {}
    for nombre, (tipo, _) in bloques.items():
        if tipo != "Table":
            continue
        tabla = nombre.split(".")[-1]
        nulables = []
        for col, atributos in columnas(nombre, bloques):
            if col == "id" or "not null" in atributos or "primary key" in atributos:
                continue
            nulables.append(a_pascal(col))
        por_tabla[tabla] = sorted(set(nulables))

    lineas = [
        "// Code generated by services/generar_campos_nulables.py; DO NOT EDIT.",
        "",
        "package services",
        "",
        "// camposNulables lista, por tabla del modelo, los campos escalares que admiten null",
        "// (columnas sin [not null] en el DBML), en PascalCase como en la configuración.",
        "//",
        "// TODO: Mover la nulabilidad a la configuración generada por utils/generador_configuracion",
        "// y eliminar este archivo; hoy el DBML es la única fuente de esta información.",
        "var camposNulables = map[string]map[string]bool{",
    ]
    for tabla in sorted(por_tabla):
        lineas.append(f'\t"{tabla}": {{')
        for campo in por_tabla[tabla]:
            lineas.append(f'\t\t"{campo}": true,')
        lineas.append("\t},")
    lineas.append("}")
    lineas.append("")

    with open(SALIDA, "w", encoding="utf-8") as f:
        f.write("\n".join(lineas))
    # La salida se formatea con gofmt para que dos generaciones den bytes idénticos.
    subprocess.run(["gofmt", "-w", SALIDA], check=True)
    print(f"{SALIDA}: {len(por_tabla)} tablas, {sum(len(v) for v in por_tabla.values())} campos nulables")


if __name__ == "__main__":
    sys.exit(main())
